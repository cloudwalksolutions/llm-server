#!/usr/bin/env bash
# Deploy config/llama.yaml to the target's per-model llama-server instances.
#
# Owns /opt/llm/instances/<name>.conf, consumed by llama-server@<name>.service.
# Restarts only instances whose config changed.
#
# Usage:
#   ./scripts/deploy-llama.sh                 apply
#   ./scripts/deploy-llama.sh --dry-run       diff what would change
#   ./scripts/deploy-llama.sh --render NAME   print one instance conf
#
# -E is required or the ERR trap won't fire inside functions.
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

MODE="apply"
RENDER_ONE=""
case "${1:-}" in
    --dry-run) MODE="dry-run" ;;
    --render)  MODE="render"; RENDER_ONE="${2:-}" ;;
    "")        MODE="apply" ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
esac

load_config "${LLAMA_CONFIG:-config/llama.yaml}" || exit 1

TIMESTAMP=$(date +"%Y%m%d-%H%M%S")

# ── Renderer ──────────────────────────────────────────────────────────────────
# The API key stays owned by the target; it's read back, not rewritten.
render_instance_conf() {
    local name="$1" api_key="$2"
    load_instance "$name" || return 1
    cat <<EOF
# llama-server instance config — generated by deploy-llama.sh
# Edit config/llama.yaml + 'make deploy' instead of editing this file directly.
LLAMA_PORT=$INST_PORT
MODEL_FILE=$INST_MODEL_FILE
CONTEXT_SIZE=$INST_TOTAL_CONTEXT
PARALLEL_SLOTS=$INST_PARALLEL_SLOTS
BATCH_SIZE=$INST_BATCH_SIZE
UBATCH_SIZE=$INST_UBATCH_SIZE
THREADS_GEN=$INST_THREADS_GEN
THREADS_BATCH=$INST_THREADS_BATCH
THREADS_HTTP=$INST_THREADS_HTTP
CACHE_REUSE=$INST_CACHE_REUSE
CACHE_TYPE_K=$INST_CACHE_TYPE_K
CACHE_TYPE_V=$INST_CACHE_TYPE_V
FLASH_ATTN=$INST_FLASH_ATTN
DRAFT_MODEL=$INST_DRAFT_MODEL
DRAFT_MAX=$INST_DRAFT_MAX
LLAMA_API_KEY=$api_key
CONTAINER_IMAGE=$INST_CONTAINER_IMAGE
EOF
}

if [[ "$MODE" == "render" ]]; then
    [[ -n "$RENDER_ONE" ]] || { echo "--render needs an instance name" >&2; exit 2; }
    render_instance_conf "$RENDER_ONE" "${BASE_LLAMA_API_KEY:-<preserved-from-target>}"
    exit 0
fi

# Assert the derived -c actually yields the requested per-request window once
# llama.cpp applies its 256-token padding.
check_derivation() {
    local n bad=0 eff
    for n in "${INSTANCE_NAMES[@]}"; do
        load_instance "$n" || return 1
        eff=$(effective_ctx_per_request "$INST_TOTAL_CONTEXT" "$INST_PARALLEL_SLOTS" "$INST_KV_UNIFIED")
        if [[ "$eff" != "$INST_CONTEXT_PER_REQUEST" ]]; then
            echo -e "${RED}$n: asked for $INST_CONTEXT_PER_REQUEST/request but llama.cpp would give $eff${NC}" >&2
            bad=1
        fi
    done
    ((bad == 0))
}

echo -e "${CYAN}[1/7]${NC} Config:"
print_config
echo ""
check_derivation || { echo -e "${RED}Derivation check failed${NC}" >&2; exit 1; }

echo -e "${CYAN}[2/7]${NC} Connecting to ${REMOTE_USER}@${REMOTE_HOST}..."
test_ssh || { echo -e "${RED}Connection failed${NC}" >&2; exit 1; }

echo -e "${CYAN}[3/7]${NC} Verifying target layout..."
remote_exec "test -d $INSTANCES_DIR" || {
    echo -e "${RED}$INSTANCES_DIR does not exist on the target.${NC}" >&2
    echo "This script expects the templated llama-server@<name>.service layout." >&2
    exit 1
}
remote_exec "systemctl cat llama-server@.service >/dev/null 2>&1" || {
    echo -e "${RED}Target has no llama-server@.service template.${NC}" >&2
    exit 1
}
if ! remote_exec "command -v $RUNTIME_ENGINE >/dev/null 2>&1"; then
    echo -e "${RED}Target has no '$RUNTIME_ENGINE'.${NC}" >&2
    exit 1
fi

for name in "${INSTANCE_NAMES[@]}"; do
    remote_exec "test -f $INSTANCES_DIR/$name.conf" || {
        echo -e "${RED}No $INSTANCES_DIR/$name.conf on the target.${NC}" >&2
        echo "Adding an instance also needs an nginx router entry — do that first." >&2
        exit 1
    }
done

# nginx routes by this map; changing a port without it breaks routing.
echo -e "${CYAN}[4/7]${NC} Checking nginx router map..."
ROUTER_JSON=$(remote_exec "cat $ROUTER_MAP 2>/dev/null" || echo "")
for name in "${INSTANCE_NAMES[@]}"; do
    load_instance "$name"
    mapped=$(jq -r --arg n "$name" '.[$n] // ""' <<<"$ROUTER_JSON" 2>/dev/null || echo "")
    if [[ -z "$mapped" ]]; then
        echo -e "  ${YELLOW}warn${NC} $name is not in $ROUTER_MAP — nginx cannot route to it"
    elif [[ "$mapped" != "127.0.0.1:$INST_PORT" ]]; then
        echo -e "  ${RED}$name: router says $mapped but config says port $INST_PORT${NC}" >&2
        echo "  Fix $ROUTER_MAP (and reload nginx) or the port in llama.yaml." >&2
        exit 1
    fi
done
echo "  router map agrees with configured ports"

# ── Work out what actually changes ────────────────────────────────────────────
echo -e "${CYAN}[5/7]${NC} Comparing against the target..."
CHANGED=()
declare -A RENDERED
for name in "${INSTANCE_NAMES[@]}"; do
    key=$(remote_conf_value "$INSTANCES_DIR/$name.conf" LLAMA_API_KEY)
    if [[ -z "$key" ]]; then
        echo -e "${RED}$name: could not read LLAMA_API_KEY from the target.${NC}" >&2
        echo "Refusing to write a config that would disable auth." >&2
        exit 1
    fi
    new=$(render_instance_conf "$name" "$key")
    RENDERED["$name"]="$new"
    cur=$(remote_exec "cat $INSTANCES_DIR/$name.conf 2>/dev/null" || echo "")

    if [[ "$cur" == "$new" ]]; then
        echo -e "  ${GREEN}unchanged${NC}  $name"
    else
        CHANGED+=("$name")
        echo -e "  ${YELLOW}CHANGED${NC}    $name"
        diff -u <(printf '%s\n' "$cur" | grep -vE '^LLAMA_API_KEY=') \
                <(printf '%s\n' "$new" | grep -vE '^LLAMA_API_KEY=') \
            | sed 's/^/      /' || true
    fi
done

if ((${#CHANGED[@]} == 0)); then
    echo -e "\n${GREEN}Nothing to do — target already matches config.${NC}"
    exit 0
fi

if [[ "$MODE" == "dry-run" ]]; then
    echo -e "\n${YELLOW}DRY RUN — would restart: ${CHANGED[*]}${NC}"
    echo -e "${YELLOW}Run 'make deploy' to apply${NC}"
    exit 0
fi

# ── Apply ─────────────────────────────────────────────────────────────────────
ROLLBACK=()
rb() { ROLLBACK+=("$*"); }

health_check() {
    local name="$1" port="$2" timeout="${3:-300}" start now code n0 ncur
    start=$(date +%s)
    n0=$(remote_exec "systemctl show -p NRestarts --value llama-server@$name" 2>/dev/null || echo 0)

    while :; do
        now=$(date +%s)
        ((now - start >= timeout)) && { echo "  health check timed out after ${timeout}s" >&2; return 1; }

        # Restart=always lets a crash-looping unit answer from a stale container
        ncur=$(remote_exec "systemctl show -p NRestarts --value llama-server@$name" 2>/dev/null || echo "$n0")
        if [[ "$ncur" =~ ^[0-9]+$ && "$n0" =~ ^[0-9]+$ ]] && ((ncur > n0)); then
            echo "  crash loop: restarted $((ncur - n0))x during health check" >&2
            return 1
        fi

        code=$(remote_exec "curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:$port/health" 2>/dev/null || echo 000)
        [[ "$code" == "200" ]] && return 0
        printf '.'
        sleep 3
    done
}

run_rollback() {
    echo -e "\n${RED}Deploy failed — rolling back${NC}" >&2
    local i
    for ((i = ${#ROLLBACK[@]} - 1; i >= 0; i--)); do
        echo "  undo: ${ROLLBACK[i]}" >&2
        remote_exec_sudo "${ROLLBACK[i]}" || echo -e "  ${RED}rollback step failed${NC}" >&2
    done
    for n in "${CHANGED[@]}"; do
        remote_exec_sudo "systemctl restart llama-server@$n" || true
    done
    echo -e "${YELLOW}Rolled back. Verify with 'make verify'.${NC}" >&2
    exit 1
}
trap run_rollback ERR

echo -e "${CYAN}[6/7]${NC} Writing configs for: ${CHANGED[*]}"
for name in "${CHANGED[@]}"; do
    remote_exec_sudo "cp $INSTANCES_DIR/$name.conf $INSTANCES_DIR/$name.conf.backup.$TIMESTAMP"
    rb "cp $INSTANCES_DIR/$name.conf.backup.$TIMESTAMP $INSTANCES_DIR/$name.conf"

    printf '%s\n' "${RENDERED[$name]}" | remote_write_sudo "$INSTANCES_DIR/$name.conf" 640

    # Read back before restarting. A truncated or empty write yields a unit
    # whose every variable is unset, which fails as an opaque podman error.
    readback=$(remote_exec "cat $INSTANCES_DIR/$name.conf 2>/dev/null" || echo "")
    if [[ "$readback" != "${RENDERED[$name]}" ]]; then
        echo -e "${RED}$name: written config does not match what was rendered${NC}" >&2
        diff -u <(printf '%s\n' "${RENDERED[$name]}") <(printf '%s\n' "$readback") | head -20 >&2
        false
    fi
    echo -e "  ${GREEN}written + verified${NC}  $name"
done

echo -e "${CYAN}[7/7]${NC} Restarting changed instances (model load takes a minute)..."
for name in "${CHANGED[@]}"; do
    load_instance "$name"
    echo -n "  $name "
    remote_exec_sudo "systemctl restart llama-server@$name"
    health_check "$name" "$INST_PORT" 300
    echo -e " ${GREEN}healthy${NC}"
done

trap - ERR

echo ""
echo -e "${GREEN}✓ Deployed${NC}"
for name in "${CHANGED[@]}"; do
    load_instance "$name"
    echo -e "  $name: ${GREEN}$INST_CONTEXT_PER_REQUEST${NC} tokens/request × $INST_PARALLEL_SLOTS slots (-c $INST_TOTAL_CONTEXT)"
done
echo ""
echo -e "Next: ${BLUE}make verify${NC} | ${BLUE}make test-context${NC}"
