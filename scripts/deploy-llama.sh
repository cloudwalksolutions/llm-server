#!/usr/bin/env bash
# Deploy config/llama.yaml to the target's per-model llama-server instances.
#
# Owns two things on the target:
#   <instances_dir>/<name>.conf   per-model settings, expanded by systemd as ${VAR}
#   llama-server@.service         the unit, rendered from
#                                 templates/llama-server@.service.in — i.e. the argv
#
# Restarts only instances whose conf changed — EXCEPT that all instances share the
# unit template, so a change there restarts every one of them. --dry-run says which.
#
# Usage:
#   ./scripts/deploy-llama.sh                 apply
#   ./scripts/deploy-llama.sh --dry-run       diff what would change
#   ./scripts/deploy-llama.sh --render NAME   print one instance conf
#   ./scripts/deploy-llama.sh --render unit   print the rendered systemd unit
#   ./scripts/deploy-llama.sh --check         validate config only, no network
#
# -E is required or the ERR trap won't fire inside functions.
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

MODE="apply"
RENDER_ONE=""
case "${1:-}" in
    --dry-run) MODE="dry-run" ;;
    --render)  MODE="render"; RENDER_ONE="${2:-}" ;;
    --check)   MODE="check" ;;
    "")        MODE="apply" ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
esac

load_config "${LLAMA_CONFIG:-config/llama.yaml}" || exit 1

TIMESTAMP=$(date +"%Y%m%d-%H%M%S")

# ── Renderer ──────────────────────────────────────────────────────────────────
# The API key stays owned by the target; it's read back, not rewritten.
render_instance_conf() {
    local name="$1" api_key="$2"
    load_instance "$name" || return 1
    cat <<EOF
# llama-server instance config — generated by deploy-llama.sh
# Edit config/llama.yaml + 'make deploy' instead of editing this file directly.
LLAMA_PORT=$INST_PORT
MODEL_FILE=$INST_MODEL_FILE
CONTEXT_SIZE=$INST_TOTAL_CONTEXT
PARALLEL_SLOTS=$INST_PARALLEL_SLOTS
KV_UNIFIED=$INST_KV_UNIFIED
BATCH_SIZE=$INST_BATCH_SIZE
UBATCH_SIZE=$INST_UBATCH_SIZE
THREADS_GEN=$INST_THREADS_GEN
THREADS_BATCH=$INST_THREADS_BATCH
THREADS_HTTP=$INST_THREADS_HTTP
CACHE_REUSE=$INST_CACHE_REUSE
CACHE_TYPE_K=$INST_CACHE_TYPE_K
CACHE_TYPE_V=$INST_CACHE_TYPE_V
FLASH_ATTN=$INST_FLASH_ATTN
DRAFT_MODEL=$INST_DRAFT_MODEL
DRAFT_MAX=$INST_DRAFT_MAX
MMPROJ_FILE=$INST_MMPROJ_FILE
IMAGE_MIN_TOKENS=$INST_IMAGE_MIN_TOKENS
SPEC_TYPE=$INST_SPEC_TYPE
REASONING=$INST_REASONING
REASONING_BUDGET=$INST_REASONING_BUDGET
CACHE_RAM=$INST_CACHE_RAM
REASONING_BUDGET_MESSAGE="$INST_REASONING_BUDGET_MESSAGE"
SAMPLING_ARGS="$INST_SAMPLING_ARGS"
LLAMA_API_KEY=$api_key
CONTAINER_IMAGE=$INST_CONTAINER_IMAGE
EOF
}

# ── Unit template renderer ────────────────────────────────────────────────────
# The template is shared by every instance, so it is rendered once from
# runtime/resources settings only — never from per-instance values. Anything
# per-instance must go through the conf file above, which systemd expands as
# ${VAR}, and those are deliberately left untouched here.
UNIT_TEMPLATE="$SCRIPT_DIR/../templates/llama-server@.service.in"
ROUTER_TEMPLATE="$SCRIPT_DIR/../templates/llama-router.conf.in"
ROUTER_JS_SOURCE="$SCRIPT_DIR/../templates/llama-router.js"

render_router() {
    local backends="" key_check_port="" port name body
    for port in $(for name in "${INSTANCE_NAMES[@]}"; do load_instance "$name" && echo "$INST_PORT"; done | sort -un); do
        key_check_port="${key_check_port:-$port}"
        backends+="
    location @backend_127_0_0_1_$port {
        internal;
        proxy_pass http://127.0.0.1:$port;
        proxy_http_version 1.1;
        proxy_set_header Connection \"\";
        proxy_set_header Host \$host;
        proxy_set_header Authorization \$http_authorization;
        proxy_buffering off;
        proxy_request_buffering on;
        proxy_cache off;
        proxy_read_timeout 1h;
        proxy_send_timeout 1h;
        chunked_transfer_encoding on;
        gzip off;
    }"
    done
    body=$(<"$ROUTER_TEMPLATE")
    body="${body//@ROUTER_JS@/$ROUTER_JS}"
    body="${body//@BACKENDS@/$backends}"
    [[ -n "$ROUTER_DEFAULT" ]] && load_instance "$ROUTER_DEFAULT" && key_check_port="$INST_PORT"
    body="${body//@KEY_CHECK_PORT@/$key_check_port}"
    printf '%s\n' "$body"
}

render_unit() {
    [[ -f "$UNIT_TEMPLATE" ]] || {
        echo -e "${RED}missing $UNIT_TEMPLATE${NC}" >&2; return 1; }

    local engine_bin gpu_args server_cmd body
    case "$RUNTIME_ENGINE" in
        podman) engine_bin="/usr/bin/podman" ;;
        docker) engine_bin="/usr/bin/docker" ;;
    esac

    # Kept as literal indented blocks with trailing continuations so the rendered
    # ExecStart stays one shell command.
    case "$RUNTIME_GPU" in
        amd)
            gpu_args='        --device /dev/kfd \
        --device /dev/dri \
        --group-add video \
        --security-opt seccomp=unconfined \'
            # The AMD toolbox images ship a shell with llama-server on PATH.
            server_cmd="llama-server"
            ;;
        nvidia)
            gpu_args='        --gpus all \'
            # ggml-org's CUDA server image has llama-server as its ENTRYPOINT, so
            # naming it again would be passed as a model argument.
            server_cmd=""
            ;;
    esac

    body=$(<"$UNIT_TEMPLATE")
    body="${body//@ENGINE_BIN@/$engine_bin}"
    body="${body//@GPU_ARGS@/$gpu_args}"
    body="${body//@SERVER_CMD@/$server_cmd}"
    body="${body//@INSTANCES_DIR@/$INSTANCES_DIR}"
    body="${body//@MODELS_DIR@/$MODELS_DIR}"
    body="${body//@FFMPEG_DIR@/$FFMPEG_DIR}"
    body="${body//@LIMIT_NOFILE@/$RES_LIMIT_NOFILE}"
    body="${body//@LIMIT_MEMLOCK@/$RES_LIMIT_MEMLOCK}"

    # An unresolved placeholder would install a unit systemd cannot start.
    if grep -q '@[A-Z_]\+@' <<<"$body"; then
        echo -e "${RED}unresolved placeholders in the unit template:${NC}" >&2
        grep -o '@[A-Z_]\+@' <<<"$body" | sort -u | sed 's/^/  /' >&2
        return 1
    fi
    printf '%s\n' "$body"
}

if [[ "$MODE" == "render" ]]; then
    [[ -n "$RENDER_ONE" ]] || { echo "--render needs an instance name" >&2; exit 2; }
    if [[ "$RENDER_ONE" == "--unit" || "$RENDER_ONE" == "unit" ]]; then
        render_unit
        exit 0
    fi
    if [[ "$RENDER_ONE" == "comfyui" ]]; then
        render_comfyui_unit
        exit 0
    fi
    if [[ "$RENDER_ONE" == "router" ]]; then
        render_router
        exit 0
    fi
    render_instance_conf "$RENDER_ONE" "${BASE_LLAMA_API_KEY:-<preserved-from-target>}"
    exit 0
fi

# Assert the derived -c actually yields the requested per-request window once
# llama.cpp applies its 256-token padding.
check_derivation() {
    local n bad=0 eff
    for n in "${INSTANCE_NAMES[@]}"; do
        load_instance "$n" || return 1
        [[ "$INST_KV_UNIFIED" == "true" ]] && continue
        eff=$(effective_ctx_per_request "$INST_TOTAL_CONTEXT" "$INST_PARALLEL_SLOTS" "$INST_KV_UNIFIED")
        if [[ "$eff" != "$INST_CONTEXT_PER_REQUEST" ]]; then
            echo -e "${RED}$n: asked for $INST_CONTEXT_PER_REQUEST/request but llama.cpp would give $eff${NC}" >&2
            bad=1
        fi
    done
    ((bad == 0))
}

# Validate and stop. --render returns before check_derivation ever runs, so
# without this the one invariant this script exists to enforce is unreachable
# from an offline test.
if [[ "$MODE" == "check" ]]; then
    for name in "${INSTANCE_NAMES[@]}"; do
        load_instance "$name" >/dev/null || exit 1
    done
    check_derivation || exit 1
    echo -e "${GREEN}config OK${NC} — ${#INSTANCE_NAMES[@]} instances validated"
    exit 0
fi

echo -e "${CYAN}[1/7]${NC} Config:"
print_config
echo ""
check_derivation || { echo -e "${RED}Derivation check failed${NC}" >&2; exit 1; }

echo -e "${CYAN}[2/7]${NC} Connecting to ${REMOTE_USER}@${REMOTE_HOST}..."
test_ssh || { echo -e "${RED}Connection failed${NC}" >&2; exit 1; }

echo -e "${CYAN}[3/7]${NC} Verifying target layout..."
remote_exec "test -d $INSTANCES_DIR" || {
    echo -e "${RED}$INSTANCES_DIR does not exist on the target.${NC}" >&2
    echo "This script expects the templated llama-server@<name>.service layout." >&2
    exit 1
}
remote_exec "systemctl cat llama-server@.service >/dev/null 2>&1" || {
    echo -e "${RED}Target has no llama-server@.service template.${NC}" >&2
    exit 1
}
if ! remote_exec "command -v $RUNTIME_ENGINE >/dev/null 2>&1"; then
    echo -e "${RED}Target has no '$RUNTIME_ENGINE'.${NC}" >&2
    exit 1
fi

NEW_INSTANCES=()
EXISTING_INSTANCES=()
for name in "${INSTANCE_NAMES[@]}"; do
    if remote_exec "test -f $INSTANCES_DIR/$name.conf"; then
        EXISTING_INSTANCES+=("$name")
        continue
    fi
    load_instance "$name"
    remote_exec "test -f $MODELS_DIR/$INST_MODEL_FILE" || {
        echo -e "${RED}$name is new, but $MODELS_DIR/$INST_MODEL_FILE is not on the target.${NC}" >&2
        exit 1
    }
    NEW_INSTANCES+=("$name")
    echo -e "  ${YELLOW}NEW${NC}        $name ($INST_MODEL_FILE)"
done
((${#EXISTING_INSTANCES[@]} > 0)) || {
    echo -e "${RED}No existing instance to take the API key from; this script never invents one.${NC}" >&2
    exit 1
}

for name in "${INSTANCE_NAMES[@]}"; do
    load_instance "$name"
    [[ -z "$INST_MMPROJ_FILE" ]] && continue
    remote_exec "test -f $MODELS_DIR/$INST_MMPROJ_FILE" || {
        echo -e "${RED}$name needs $MODELS_DIR/$INST_MMPROJ_FILE, which is not on the target (make add-model).${NC}" >&2
        exit 1
    }
done

RETIRED_INSTANCES=()
for conf in $(remote_exec "ls $INSTANCES_DIR/*.conf 2>/dev/null" || true); do
    name=$(basename "$conf" .conf)
    [[ " ${INSTANCE_NAMES[*]} " == *" $name "* ]] && continue
    RETIRED_INSTANCES+=("$name")
    echo -e "  ${YELLOW}RETIRE${NC}     $name (disabled or no longer in config)"
done

# nginx routes by this map; changing a port without it breaks routing.
echo -e "${CYAN}[4/7]${NC} Checking nginx router map..."
ROUTER_JSON=$(remote_exec "cat $ROUTER_MAP 2>/dev/null" || echo "")
NEW_ROUTER_JSON="$ROUTER_JSON"
for name in "${INSTANCE_NAMES[@]}"; do
    load_instance "$name"
    mapped=$(jq -r --arg n "$name" '.[$n] // ""' <<<"$ROUTER_JSON" 2>/dev/null || echo "")
    if [[ -z "$mapped" && " ${NEW_INSTANCES[*]} " == *" $name "* ]]; then
        NEW_ROUTER_JSON=$(router_map_with "$NEW_ROUTER_JSON" "$name" "$INST_PORT")
        echo -e "  ${YELLOW}NEW${NC}        route $name -> 127.0.0.1:$INST_PORT"
    elif [[ -z "$mapped" ]]; then
        echo -e "  ${YELLOW}warn${NC} $name is not in $ROUTER_MAP — nginx cannot route to it"
    elif [[ "$mapped" != "127.0.0.1:$INST_PORT" ]]; then
        echo -e "  ${RED}$name: router says $mapped but config says port $INST_PORT${NC}" >&2
        echo "  Fix $ROUTER_MAP (and reload nginx) or the port in llama.yaml." >&2
        exit 1
    fi
done
if [[ -n "$ROUTER_DEFAULT" ]]; then
    [[ " ${INSTANCE_NAMES[*]} " == *" $ROUTER_DEFAULT "* ]] \
        || { echo -e "  ${RED}runtime.router_default names $ROUTER_DEFAULT, which is not an instance${NC}" >&2; exit 1; }
    load_instance "$ROUTER_DEFAULT"
    NEW_ROUTER_JSON=$(router_map_default "$NEW_ROUTER_JSON" "$INST_PORT")
    [[ "$(jq -r '._default // ""' <<<"$ROUTER_JSON")" == "127.0.0.1:$INST_PORT" ]] \
        || echo -e "  ${YELLOW}CHANGED${NC}    route _default -> $ROUTER_DEFAULT (127.0.0.1:$INST_PORT)"
fi
for name in "${RETIRED_INSTANCES[@]}"; do
    mapped=$(jq -r --arg n "$name" '.[$n] // ""' <<<"$ROUTER_JSON")
    if [[ -n "$mapped" && "$mapped" == "$(jq -r '._default // ""' <<<"$NEW_ROUTER_JSON")" ]] \
        && ! jq -e --arg n "$name" --arg m "$mapped" 'to_entries | any(.key != $n and .key != "_default" and .value == $m)' <<<"$NEW_ROUTER_JSON" >/dev/null; then
        echo -e "  ${RED}$name is the router's _default; point _default elsewhere before retiring it${NC}" >&2
        exit 1
    fi
    NEW_ROUTER_JSON=$(router_map_without "$NEW_ROUTER_JSON" "$name")
    echo -e "  ${YELLOW}RETIRE${NC}     route $name"
done
echo "  router map agrees with configured ports"

# ── Work out what actually changes ────────────────────────────────────────────
echo -e "${CYAN}[5/7]${NC} Comparing against the target..."
CHANGED=()
declare -A RENDERED

# The unit template first, because a change to it affects every instance.
UNIT_CHANGED=0
NEW_UNIT=$(render_unit) || { echo -e "${RED}could not render the unit${NC}" >&2; exit 1; }
CUR_UNIT=$(remote_exec "cat $UNIT_PATH 2>/dev/null" || echo "")
if [[ -z "$CUR_UNIT" ]]; then
    echo -e "  ${YELLOW}NEW${NC}        $UNIT_PATH (not present on the target)"
    UNIT_CHANGED=1
elif [[ "$CUR_UNIT" == "$NEW_UNIT" ]]; then
    echo -e "  ${GREEN}unchanged${NC}  $UNIT_PATH"
else
    UNIT_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $UNIT_PATH"
    diff -u <(printf '%s\n' "$CUR_UNIT") <(printf '%s\n' "$NEW_UNIT") | sed 's/^/      /' || true
fi
FFMPEG_CHANGED=0
if [[ "$(remote_exec "test -x $FFMPEG_DIR/ffmpeg && test -x $FFMPEG_DIR/ffprobe && cat $FFMPEG_DIR/.sha256" 2>/dev/null || true)" == "$FFMPEG_SHA256" ]]; then
    echo -e "  ${GREEN}unchanged${NC}  $FFMPEG_DIR"
else
    FFMPEG_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $FFMPEG_DIR ($FFMPEG_URL)"
fi
for name in "${INSTANCE_NAMES[@]}"; do
    key=$(remote_conf_value "$INSTANCES_DIR/${EXISTING_INSTANCES[0]}.conf" LLAMA_API_KEY)
    [[ " ${NEW_INSTANCES[*]} " == *" $name "* ]] \
        || key=$(remote_conf_value "$INSTANCES_DIR/$name.conf" LLAMA_API_KEY)
    if [[ -z "$key" ]]; then
        echo -e "${RED}$name: could not read LLAMA_API_KEY from the target.${NC}" >&2
        echo "Refusing to write a config that would disable auth." >&2
        exit 1
    fi
    new=$(render_instance_conf "$name" "$key")
    RENDERED["$name"]="$new"
    cur=$(remote_exec "cat $INSTANCES_DIR/$name.conf 2>/dev/null" || echo "")

    if [[ "$cur" == "$new" ]]; then
        echo -e "  ${GREEN}unchanged${NC}  $name"
    else
        CHANGED+=("$name")
        echo -e "  ${YELLOW}CHANGED${NC}    $name"
        diff -u <(printf '%s\n' "$cur" | grep -vE '^LLAMA_API_KEY=') \
                <(printf '%s\n' "$new" | grep -vE '^LLAMA_API_KEY=') \
            | sed 's/^/      /' || true
    fi
done

# CHANGED is what gets REWRITTEN; RESTART is what gets bounced. They differ
# because every instance shares the unit template, so a template change restarts
# instances whose own conf is untouched. Keeping them separate avoids rewriting
# (and backing up) confs that are already correct.
RESTART=("${CHANGED[@]}")
if ((UNIT_CHANGED)); then
    if ((${#CHANGED[@]} < ${#INSTANCE_NAMES[@]})); then
        echo -e "\n  ${YELLOW}the unit template changed — every instance restarts,${NC}"
        echo -e "  ${YELLOW}not just the ones whose own conf changed${NC}"
    fi
    RESTART=("${INSTANCE_NAMES[@]}")
fi

NEW_ROUTER_CONF=$(render_router)
NEW_ROUTER_JS=$(<"$ROUTER_JS_SOURCE")
CUR_ROUTER_CONF=$(remote_exec "cat $ROUTER_CONF 2>/dev/null" || echo "")
CUR_ROUTER_JS=$(remote_exec "cat $ROUTER_JS 2>/dev/null" || echo "")
ROUTER_FILES_CHANGED=0
for pair in "$ROUTER_CONF:CONF" "$ROUTER_JS:JS"; do
    path="${pair%:*}"; cur_var="CUR_ROUTER_${pair##*:}"; new_var="NEW_ROUTER_${pair##*:}"
    if [[ "${!cur_var}" == "${!new_var}" ]]; then
        echo -e "  ${GREEN}unchanged${NC}  $path"
    else
        ROUTER_FILES_CHANGED=1
        echo -e "  ${YELLOW}CHANGED${NC}    $path"
        diff -u <(printf '%s\n' "${!cur_var}") <(printf '%s\n' "${!new_var}") | sed 's/^/      /' || true
    fi
done
ROUTER_CHANGED=0
[[ "$(jq -cS . <<<"$NEW_ROUTER_JSON")" != "$(jq -cS . <<<"$ROUTER_JSON")" ]] && ROUTER_CHANGED=1
((ROUTER_FILES_CHANGED)) && ROUTER_CHANGED=1

NEW_COMFYUI_UNIT=""
[[ "$COMFYUI_CONFIGURED" == true ]] && NEW_COMFYUI_UNIT=$(render_comfyui_unit)
CUR_COMFYUI_UNIT=$(remote_exec "cat $COMFYUI_UNIT_PATH 2>/dev/null" || echo "")
COMFYUI_UNIT_CHANGED=0
if [[ "$CUR_COMFYUI_UNIT" == "$NEW_COMFYUI_UNIT" ]]; then
    [[ -n "$NEW_COMFYUI_UNIT" ]] && echo -e "  ${GREEN}unchanged${NC}  $COMFYUI_UNIT_PATH"
else
    COMFYUI_UNIT_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_UNIT_PATH"
    diff -u <(printf '%s\n' "$CUR_COMFYUI_UNIT") <(printf '%s\n' "$NEW_COMFYUI_UNIT") | sed 's/^/      /' || true
fi
COMFYUI_ACTIVE=$(remote_exec "systemctl is-active comfyui" 2>/dev/null || true)
COMFYUI_AT_BOOT=$(remote_exec "systemctl is-enabled comfyui" 2>/dev/null || true)
COMFYUI_START=0
COMFYUI_STOP=0
if [[ "$COMFYUI_ENABLED" == true ]]; then
    if ((COMFYUI_UNIT_CHANGED)) || [[ "$COMFYUI_ACTIVE" != active || "$COMFYUI_AT_BOOT" != enabled ]]; then
        COMFYUI_START=1
    fi
elif [[ "$COMFYUI_ACTIVE" == active || "$COMFYUI_AT_BOOT" == enabled ]]; then
    COMFYUI_STOP=1
fi
((COMFYUI_START)) && echo -e "  ${YELLOW}START${NC}      comfyui (enabled in $COMFYUI_CONFIG)"
((COMFYUI_STOP)) && echo -e "  ${YELLOW}STOP${NC}       comfyui (disabled or not configured)"
NEW_MCP_UNIT=""
[[ "$COMFYUI_CONFIGURED" == true ]] && NEW_MCP_UNIT=$(render_comfyui_mcp_unit)
CUR_MCP_UNIT=$(remote_exec "cat $COMFYUI_MCP_UNIT_PATH 2>/dev/null" || echo "")
MCP_UNIT_CHANGED=0
if [[ "$CUR_MCP_UNIT" == "$NEW_MCP_UNIT" ]]; then
    [[ -n "$NEW_MCP_UNIT" ]] && echo -e "  ${GREEN}unchanged${NC}  $COMFYUI_MCP_UNIT_PATH"
else
    MCP_UNIT_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_MCP_UNIT_PATH"
    diff -u <(printf '%s\n' "$CUR_MCP_UNIT") <(printf '%s\n' "$NEW_MCP_UNIT") | sed 's/^/      /' || true
fi
MCP_STAGE=$(mktemp -d)
trap 'rm -rf "$MCP_STAGE"' EXIT
MCP_CODE_CHANGED=0
if [[ "$COMFYUI_CONFIGURED" == true ]]; then
    stage_comfyui_mcp "$MCP_STAGE"
    NEW_MCP_MANIFEST=$(cd "$MCP_STAGE" && bash -c "$COMFYUI_MCP_MANIFEST")
    CUR_MCP_MANIFEST=$(remote_exec "cd $(_shq "$COMFYUI_MCP_DIR") 2>/dev/null && $COMFYUI_MCP_MANIFEST" 2>/dev/null || echo "")
    if [[ "$CUR_MCP_MANIFEST" == "$NEW_MCP_MANIFEST" ]]; then
        echo -e "  ${GREEN}unchanged${NC}  $COMFYUI_MCP_DIR"
    else
        MCP_CODE_CHANGED=1
        echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_MCP_DIR"
        diff <(awk '{print $2}' <<<"$CUR_MCP_MANIFEST") <(awk '{print $2}' <<<"$NEW_MCP_MANIFEST") | sed 's/^/      /' || true
    fi
fi
MCP_ACTIVE=$(remote_exec "systemctl is-active comfyui-mcp" 2>/dev/null || true)
MCP_AT_BOOT=$(remote_exec "systemctl is-enabled comfyui-mcp" 2>/dev/null || true)
MCP_START=0
MCP_STOP=0
if [[ "$COMFYUI_ENABLED" == true ]]; then
    if ((COMFYUI_START || MCP_UNIT_CHANGED || MCP_CODE_CHANGED)) || [[ "$MCP_ACTIVE" != active || "$MCP_AT_BOOT" != enabled ]]; then
        MCP_START=1
    fi
elif [[ "$MCP_ACTIVE" == active || "$MCP_AT_BOOT" == enabled ]]; then
    MCP_STOP=1
fi
((MCP_START)) && echo -e "  ${YELLOW}START${NC}      comfyui-mcp"
((MCP_STOP)) && echo -e "  ${YELLOW}STOP${NC}       comfyui-mcp"
COMFYUI_CHANGED=$((COMFYUI_UNIT_CHANGED || COMFYUI_START || COMFYUI_STOP || MCP_UNIT_CHANGED || MCP_CODE_CHANGED || MCP_START || MCP_STOP))

NEW_PROXY=""
NEW_KEY_MAP=""
NEW_MCP_KEY_MAP=""
if [[ "$COMFYUI_CONFIGURED" == true ]]; then
    [[ "${COMFYUI_API_KEY:-}" =~ ^[A-Za-z0-9_-]{32,}$ ]] \
        || { _cfg_err "COMFYUI_API_KEY in the env file must be 32 or more letters, digits, - or _"; exit 1; }
    [[ "${COMFYUI_MCP_KEY:-}" =~ ^[A-Za-z0-9_-]{32,}$ ]] \
        || { _cfg_err "COMFYUI_MCP_KEY in the env file must be 32 or more letters, digits, - or _"; exit 1; }
    NEW_PROXY=$(render_comfyui_proxy)
    NEW_KEY_MAP=$(render_comfyui_key_map "$COMFYUI_API_KEY")
    NEW_MCP_KEY_MAP=$(render_comfyui_key_map "$COMFYUI_MCP_KEY")
fi
CUR_PROXY=$(remote_exec "cat $COMFYUI_PROXY_PATH 2>/dev/null" || echo "")
CUR_KEY_MAP=$(remote_exec_sudo "cat $COMFYUI_KEY_MAP_PATH 2>/dev/null" || echo "")
CUR_MCP_KEY_MAP=$(remote_exec_sudo "cat $COMFYUI_MCP_KEY_MAP_PATH 2>/dev/null" || echo "")
PROXY_CHANGED=0
if [[ "$CUR_PROXY" != "$NEW_PROXY" ]]; then
    PROXY_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_PROXY_PATH"
    diff -u <(printf '%s\n' "$CUR_PROXY") <(printf '%s\n' "$NEW_PROXY") | sed 's/^/      /' || true
fi
if [[ "$CUR_KEY_MAP" != "$NEW_KEY_MAP" ]]; then
    PROXY_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_KEY_MAP_PATH (the key is not shown)"
fi
if [[ "$CUR_MCP_KEY_MAP" != "$NEW_MCP_KEY_MAP" ]]; then
    PROXY_CHANGED=1
    echo -e "  ${YELLOW}CHANGED${NC}    $COMFYUI_MCP_KEY_MAP_PATH (the key is not shown)"
fi
if [[ -n "$NEW_PROXY" ]] && ! comfyui_proxy_listening; then
    PROXY_CHANGED=1
    echo -e "  ${YELLOW}NOT LISTENING${NC} ComfyUI's proxy on $COMFYUI_API_PORT and $COMFYUI_UI_PORT"
fi

CUR_TUNNEL=$(remote_exec "cat $TUNNEL_CONFIG 2>/dev/null" || echo "")
NEW_TUNNEL="$CUR_TUNNEL"
if [[ -n "$CUR_TUNNEL" ]]; then
